"""Integrity checks for the authored curriculum, exercises and question banks."""
import re

from app import content
from app.content.modules import MODULES


def test_validate_content_clean():
    assert content.validate_content() == []


def test_all_modules_have_lessons():
    per_module = {m["id"]: 0 for m in MODULES}
    for lesson in content.lessons():
        per_module[lesson["module"]] += 1
    assert len(MODULES) == 10
    assert all(n >= 3 for n in per_module.values()), per_module


def test_lessons_have_required_sections():
    for lesson in content.lessons():
        assert len(lesson["body"]) > 1500, lesson["id"]
        assert lesson["quiz"], lesson["id"]
        assert lesson["interview"], lesson["id"]


def test_lesson_prereqs_are_acyclic():
    prereqs = {l["id"]: l["prereqs"] for l in content.lessons()}
    visiting, done = set(), set()

    def visit(node):
        assert node not in visiting, f"cycle at {node}"
        if node in done:
            return
        visiting.add(node)
        for p in prereqs[node]:
            visit(p)
        visiting.discard(node)
        done.add(node)

    for n in prereqs:
        visit(n)


def test_exercise_ids_unique_and_complete():
    sql = content.sql_exercises()
    py = content.python_exercises()
    assert len(sql) >= 30 and len(py) >= 20
    for group in (sql, py):
        ids = [e["id"] for e in group]
        assert len(ids) == len(set(ids))
        for e in group:
            assert e["hints"] and e["solution"] and e["prompt"]


def test_lesson_exercise_links_resolve():
    ids = {e["id"] for e in content.sql_exercises()} | {e["id"] for e in content.python_exercises()}
    for lesson in content.lessons():
        for ex in lesson["exercises"]:
            assert ex in ids, (lesson["id"], ex)


def test_projects():
    projects = content.projects()
    assert len(projects) == 7
    ids = [p["id"] for p in projects]
    assert len(ids) == len(set(ids))
    for p in projects:
        for field in ("requirement", "architecture", "problem", "dataset", "milestones", "checklist", "errors", "discussion", "expected"):
            assert p[field], (p["id"], field)
        step_ids = [s["id"] for m in p["milestones"] for s in m["steps"]]
        assert len(step_ids) == len(set(step_ids))


def test_scenarios_rubrics_sum_to_100():
    scenarios = content.scenarios()
    assert len(scenarios) >= 10
    assert len({s["id"] for s in scenarios}) == len(scenarios)
    for s in scenarios:
        assert sum(r["weight"] for r in s["rubric"]) == 100, s["id"]


def test_mcq_bank():
    bank = content.mcq_bank()
    assert len(bank) >= 200
    assert len({q["id"] for q in bank}) == len(bank)
    for q in bank:
        assert 0 <= q["answer"] < len(q["options"]), q["id"]
        assert len(set(q["options"])) == len(q["options"]), q["id"]
        assert q["why"], q["id"]


def test_interview_question_bank_size_and_variety():
    bank = content.question_bank()
    assert len(bank) >= 300
    assert len({q["id"] for q in bank}) == len(bank)
    assert len({q["q"] for q in bank}) == len(bank)
    assert len({q["topic"] for q in bank}) >= 12
    assert {q["level"] for q in bank} == {"beginner", "intermediate", "advanced", "expert"}
    for q in bank:
        assert q["keywords"] and q["answer"], q["id"]
        assert re.match(r"^[a-z]+-[0-9a-f]{8}$", q["id"]), q["id"]


def test_aggregators_are_repeatable():
    """Calling an aggregator twice must keep working (guards against module/function name shadowing)."""
    for fn in (content.lessons, content.sql_exercises, content.python_exercises, content.projects,
               content.scenarios, content.mcq_bank, content.question_bank):
        assert fn() and fn()


def test_static_export_is_in_sync_with_content():
    """frontend/public/static-data is generated by scripts/export_static.py; fail if it was not regenerated after a content edit."""
    import json
    from pathlib import Path

    data = Path(__file__).resolve().parents[2] / "frontend" / "public" / "static-data"
    assert (data / "modules.json").exists(), "run: backend/.venv/bin/python scripts/export_static.py"
    assert len(json.loads((data / "lessons-index.json").read_text())) == len(content.lessons())
    assert len(json.loads((data / "questions.json").read_text())) == len(content.question_bank())
    assert len(json.loads((data / "mcq.json").read_text())) == len(content.mcq_bank())
    assert len(json.loads((data / "sql-exercises.json").read_text())) == len(content.sql_exercises())
    assert len(json.loads((data / "py-exercises.json").read_text())) == len(content.python_exercises())
    exported = json.loads((data / "sql-solutions.json").read_text())
    assert {e["id"] for e in content.sql_exercises()} == set(exported)
    assert (data / "datasets.sql").read_text() == (Path(content.__file__).resolve().parents[1] / "datasets.sql").read_text()
    for lesson in content.lessons():
        assert json.loads((data / "lessons" / f"{lesson['id']}.json").read_text())["body"] == lesson["body"]
